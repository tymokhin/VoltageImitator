/* ==========================================================================
 * 10. Калібрування каналу вимірювання
 * ==========================================================================
 * offset - реальний код ADC при нульовому сигналі (у диф. режимі має бути
 *          близько 2048, але зсув підсилювача це змінює);
 * scale  - у скільки разів відлік ЗЗ треба помножити, щоб він потрапив
 *          у ту саму шкалу, що й завдання (враховує коефіцієнт дільника,
 *          підсилення й будь-яку інверсію - для інверсного каналу scale
 *          від'ємний).
 *
 * Знімається так: LOOP=0, подати відому амплітуду, подивитись FBPK у
 * відповіді GET STATE, порахувати scale = завдана_амплітуда / виміряна.
 */
#define WG_FB_OFFSET_DEFAULT           2048
#define WG_FB_SCALE_DEFAULT            1.0f

/* ==========================================================================
 * 11. Самокалібрування об'єкта на старті
 * ==========================================================================
 *
 * Замикати контур наосліп не можна. Найнебезпечніше - ЗНАК: якщо вхідне
 * коло інвертує, зворотний зв'язок стає додатним і вихід миттєво йде в
 * полицю. А без UART ні знак, ні підсилення об'єкта підібрати нема чим.
 *
 * Тому на старті прошивка сама визначає передавальну характеристику
 * «тіки duty -> відліки ADC» і лише після цього замикає контур:
 *
 *   1. SETTLE - амплітуда нуль, duty = центр. Чекаємо, поки заспокоїться
 *      LC, і водночас усереднюємо ЗЗ: це дає offset_adc (реальний код АЦП
 *      при нульовому сигналі).
 *
 *   2. PROBE - розімкнений контур, синус малої амплітуди. Накопичуємо
 *      суми Sum(ref*fb) і Sum(ref*ref) за кілька періодів. Їхнє відношення
 *      g = Sum(ref*fb)/Sum(ref*ref) - це оцінка підсилення наскрізного
 *      тракту методом найменших квадратів, РАЗОМ ЗІ ЗНАКОМ. Кореляційна
 *      оцінка стійка до пульсацій і шуму: усе, що не корельоване з
 *      завданням, у сумі прямує до нуля.
 *
 *      Якщо відгук замалий, проба повторюється з учетверо більшим
 *      feedforward, до WG_CAL_ATTEMPTS разів. Так тракт із будь-яким
 *      напруженням живлення знаходиться сам.
 *
 *   3. APPLY - усі коефіцієнти множаться на 1/P, контур замикається,
 *      амплітуда наростає до робочої.
 *
 * Проба ТІЛЬКИ ЗМІННИМ СТРУМОМ, без постійної складової: постійна на
 * трансформаторному виході ввела б осердя в насичення.
 *
 * Якщо калібрування не вдалося (обрив ЗЗ, підсилення поза межами) - канал
 * лишається в розімкненому контурі з безпечним feedforward і піднімає
 * прапорець. Сигнал усе одно генерується, просто без корекції.
 */
#define WG_AUTOCAL                     1

/* Стартовий feedforward для проби, тіки duty на відлік ADC. Свідомо малий:
 * при амплітуді проби 200 відліків це 400 тіків з 23040, тобто 1.7 %
 * модуляції - безпечно для будь-якого силового каскаду. */
#define WG_CAL_FF_PROBE                2.0f
#define WG_CAL_PROBE_AMPLITUDE_ADC     200
#define WG_CAL_ATTEMPTS                4U       /* кожна наступна x4        */
#define WG_CAL_MAX_MODULATION_TICKS    6000     /* стеля модуляції проби    */

#define WG_CAL_SETTLE_MS               150U
#define WG_CAL_SKIP_PERIODS            2U       /* пропустити перехідний    */
#define WG_CAL_MEASURE_PERIODS         6U

/* Межі правдоподібності виміряного підсилення. Поза ними вважаємо, що
 * канал вимірювання не працює, і контур не замикаємо. */
#define WG_CAL_G_MIN                   0.02f
#define WG_CAL_G_MAX                   200.0f

/* Межі підсумкового feedforward після масштабування. */
#define WG_FF_MIN                      0.1f
#define WG_FF_MAX                      200.0f

/* Частка діапазону duty, яку дозволено зайняти основній гармоніці.
 *
 * Після калібрування ff = 1/P, і потрібна модуляція duty дорівнює
 * ff * амплітуду. Якщо силовий каскад «слабкий» (мала напруга шини або
 * великий дільник у колі вимірювання), ff виходить великим, і задана
 * амплітуда просто не поміщається в діапазон шпаруватості. Раніше це дало
 * б обрізаний синус - найгірше з можливого для імітатора.
 *
 * Тому робоча амплітуда автоматично обмежується тим, що реально досяжне,
 * а решта запасу лишається регулятору на корекцію. */
#define WG_AMP_HEADROOM                0.9f

/* ==========================================================================
 * 12. Емуляція грубішої роздільності PWM (експеримент під перехід на H7)
 * ==========================================================================
 *
 * STM32H743 має HRTIM без DLL x32: роздільність 2.08 нс замість 217 пс у
 * F334. При PWM 100 кГц це 4808 кроків duty замість 46080, тобто 12.2 біта
 * замість 15.5. Питання "чи це прийнятно" не можна вирішити теоретично -
 * усе залежить від силового каскаду й LC-фільтра.
 *
 * Але його можна вирішити ПРЯМО НА ЦІЙ ПЛАТІ. 46080 / 4808 = 9.6, тому
 * квантування compare кроком 10 тіків дає точну (навіть трохи песимістичну)
 * емуляцію H743 у твоєму реальному тракті.
 *
 * Порядок експерименту - три вимірювання THD і рівнів окремих гармонік
 * при одному й тому самому завданні:
 *
 *   1) WG_DUTY_QUANT_TICKS = 0            -> рідні 15.5 біта, еталон
 *   2) WG_DUTY_QUANT_TICKS = 10, DITHER 0 -> H743 у найгіршому випадку
 *   3) WG_DUTY_QUANT_TICKS = 10, DITHER 1 -> H743 із пом'якшенням
 *
 * Якщо (3) близьке до (1) - переходити на H743 безпечно. Якщо (3) ближче
 * до (2) - силовий каскад чутливий до квантування, і треба або знижувати
 * PWM до 50 кГц (13.2 біта), або лишатись на G4 з окремим мережевим чіпом.
 *
 * Навіщо дизеринг. Похибка квантування PWM не біла - вона корельована із
 * сигналом і вилазить саме як зайві гармоніки. Для імітатора РЗА це
 * критично: ти навмисно подаєш 2-у гармоніку на рівні 15 %, і власні
 * гармоніки квантування підмішуються прямо в неї. Додавання рівномірного
 * шуму в один крок квантування ПЕРЕД усіченням розриває цю кореляцію -
 * гармоніки перетворюються на рівномірний шумовий фон, який LC-фільтр і
 * передискретизація давлять.
 */
#define WG_DUTY_QUANT_TICKS            0U   /* 0 = вимкнено; 10 ~= STM32H743 */
#define WG_DUTY_DITHER                 1    /* 1 = дизеринг перед усіченням  */

