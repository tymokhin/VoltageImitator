/**
 * @brief  Fill dma_buffer with sin/cos waveforms at 50 Hz
 */
void generate_dma_buffer(void)
{
    const float dt = 1.0f / 100000.0f; // PWM timebase at 100 kHz
    for (int i = 0; i < BUFFER_LEN; i++) {
        float t    = i * dt;
        // normalize sine/cosine to [0..1]
        float sinv = (sinf(2.0f * M_PI * 50.0f * t) + 1.0f) * 0.5f;
        //float cosv = (cosf(2.0f * M_PI * 50.0f * t) + 1.0f) * 0.5f;
        // scale to PWM_PERIOD
        uint16_t cmp1 = (uint16_t)(sinv * PWM_PERIOD + 0.5f);
        //uint16_t cmp2 = (uint16_t)(cosv * PWM_PERIOD + 0.5f);
        dma_buffer[i]     = cmp1;
        //dma_buffer[2 * i + 1] = cmp2;
    }
}
